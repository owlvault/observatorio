SELECT l.nombre_tabla, c.owner,
       CASE WHEN c.comments IS NULL THEN 'COMENTARIO_VACIO'
            ELSE 'COMENTARIO_REPETIDO_EN_' || c.repeticiones || '_TABLAS' END AS hallazgo,
       SUBSTR(c.comments,1,50) AS comentario_tabla
FROM   lake l
JOIN   com c ON c.table_name = l.nombre_tabla
WHERE  c.comments IS NULL OR c.repeticiones > 1
ORDER BY hallazgo, l.nombre_tabla;
